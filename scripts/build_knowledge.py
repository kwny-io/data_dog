# -*- coding: utf-8 -*-
"""A1：厂商文档 → 结构化知识（清洗 + 提取），产出供 Chroma 灌入的干净语料。

流程（对每个语料文件）：
  1. 清洗（clean_text）：
     - 剥掉 IDL 的 "Generated by ... idlc Python Backend" 版权头
     - 去掉网页 UI 残留：<a href>、图片 markdown ![..](..)、导航/代码窗口行
     - 折叠多余空行
  2. 结构化提取（build_*）：
     - IDL 文件 → 「字段表」知识条目（字段名 + 类型 + 组件前缀）
     - 手册/诊断 markdown → 保留文本块（错误码/阈值/LED 含义本来就在正文）
  3. 输出到 cleaned/ 目录，供 scripts/chroma_ingest.py 灌入。

每条知识条目带：
  - source：原始文件
  - structured：True（字段表）或 False（自由文本）
  - kind：schema_field / doc_note
"""
from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "vendor_docs" / "unitree"
OUT = SRC / "cleaned"

# IDL 版权头：resources `Generated by Eclipse Cyclone DDS idlc` 那一段
IDL_HEADER = re.compile(
    r'"""\s*Generated by Eclipse Cyclone DDS.*?IDL file:\s*\w+\.idl\s*"""',
    re.DOTALL,
)
# 网页/UX 残留
HTML_TAG = re.compile(r"<[^>]+>")
IMG_MD = re.compile(r"!\[[^\]]*\]\(")  # 图片 markdown 起始
LINK_TAIL = re.compile(r"\[[^\]]*\]\([^)]*\)")  # markdown 链接
BARE_URL = re.compile(r"\b(?:https?://|www\.)\S+")  # 裸 URL（无 markdown 包装）
CODE_WINDOW = re.compile(r"```|```")
GENERIC_NOISE = re.compile(
    r"(^\s*|\n)\s*(Header|Category|Example)\s*\|(\s*)?$|"
    r"(Input|Output|Parameter)\s*$",
    re.MULTILINE,
)


def clean_text(text: str, *, is_idl: bool) -> str:
    out = text
    if is_idl:
        out = IDL_HEADER.sub("", out)          # 剥版权头
        out = "\n".join(
            line for line in out.splitlines()
            if not line.lstrip().startswith(("#", "from ", "import ", "@", "KEYWORD"))
        )                                        # 去掉 python 语法噪音
    out = HTML_TAG.sub("", out)                # 剥 <a>/<img>
    out = IMG_MD.sub("", out)                  # 去图片起始
    out = LINK_TAIL.sub("", out)               # 去链接
    out = BARE_URL.sub("", out)                # 去裸 URL
    out = CODE_WINDOW.sub("", out)             # 去代码围栏
    out = GENERIC_NOISE.sub("\n", out)         # 去孤立 UI 标签行
    out = re.sub(r"\n{3,}", "\n\n", out)       # 折叠空行
    return out.strip()


def idl_fields(text: str) -> list[tuple[str, str]]:
    """从清洗后的 IDL 提取 (字段名, 类型) 对。"""
    fields = []
    for line in text.splitlines():
        m = re.match(r"\s+(\w+):\s*types\.(\w+)", line)
        if m:
            fields.append((m.group(1), m.group(2)))
    return fields


def build_schema_entries(source: str, text: str) -> list[str]:
    """IDL → 字段表知识条目（结构化）。"""
    fields = idl_fields(text)
    if not fields:
        return []
    header = f"[来源: {source}] [structured: True] [kind: schema_field]\n"
    lines = [f"{source} 定义的结构体字段："]
    for name, typ in fields:
        lines.append(f"- {name}: type={typ}")
    return [header + "\n".join(lines)]


def build_doc_entries(source: str, text: str) -> list[str]:
    """手册/诊断 markdown → 干净文本块（错误码/阈值/LED 含义保留在正文）。"""
    if not text:
        return []
    return [f"[来源: {source}] [structured: False] [kind: doc_note]\n{text}"]


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    total_entries = 0
    for f in sorted(SRC.rglob("*")):
        rel = str(f.relative_to(SRC))
        if "cleaned" in rel:
            continue
        # 用文件名匹配双后缀：.idl.txt 的 Path.suffix 只是 .txt
        is_idl = f.name.endswith(".idl.txt")
        is_md = f.name.endswith(".md")
        if not (is_idl or is_md):
            continue
        is_idl = is_idl and not is_md  # idl.txt 优先
        raw = f.read_text(encoding="utf-8", errors="replace")
        clean = clean_text(raw, is_idl=is_idl)
        entries = build_schema_entries(rel, clean) if is_idl else build_doc_entries(rel, clean)
        if not entries:
            continue
        out_file = OUT / rel
        out_file.parent.mkdir(parents=True, exist_ok=True)
        out_file.write_text("\n\n---\n\n".join(entries), encoding="utf-8")
        total_entries += len(entries)
        print(f"  {rel}: {len(entries)} 条进 {'字段表' if is_idl else '文档块'}")
    print(f"\n✅ 产出 {total_entries} 条结构化/清洗条目 → {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
